"""
generate_pymol_script.py — Generate a .pml PyMOL script for BindCraft
checkpoint trajectories.

The script renders two views:
  1. Overlay: N sampled frames superposed on step 0's target, binder colored
     blue→red by step, target gray.
  2. Per-frame gallery: each frame rendered individually, binder colored by
     B-factor (logit-space pLDDT), target gray.

Usage:
    python scripts/generate_pymol_script.py \\
        --checkpoint_dir /path/to/checkpoints \\
        --output trajectory_render.pml \\
        --n_frames 8 \\
        --render_dir pymol_renders
"""

import argparse
import colorsys
import os
from glob import glob


# ---------------------------------------------------------------------------
# Step discovery
# ---------------------------------------------------------------------------

def _discover_pdb_steps(checkpoint_dir):
    """Glob step_*/step_*_beam_0_complex.pdb, extract step numbers, return sorted list.

    Args:
        checkpoint_dir: Path to the root checkpoint directory.

    Returns:
        Sorted list of (step_num, abs_pdb_path) tuples.
    """
    pattern = os.path.join(checkpoint_dir, "step_*", "step_*_beam_0_complex.pdb")
    pdb_files = sorted(glob(pattern))

    results = []
    for pdb_path in pdb_files:
        abs_path = os.path.abspath(pdb_path)
        # Extract step number from the directory name (e.g. "step_0042")
        step_dir = os.path.dirname(abs_path)
        dir_name = os.path.basename(step_dir)
        # dir_name is like "step_0042"
        try:
            step_num = int(dir_name.split("_")[1])
        except (IndexError, ValueError):
            continue
        results.append((step_num, abs_path))

    results.sort(key=lambda t: t[0])
    return results


# ---------------------------------------------------------------------------
# Frame sampling
# ---------------------------------------------------------------------------

def _sample_frames(all_steps, n_frames):
    """Evenly sample n_frames from all_steps, always including first and last.

    Args:
        all_steps: Sorted list of (step_num, abs_pdb_path) tuples.
        n_frames:  Number of frames to sample.

    Returns:
        List of (step_num, abs_pdb_path) tuples (subset of all_steps).
    """
    if not all_steps:
        return []

    # Guard: n_frames <= 1 → return just the first
    if n_frames <= 1:
        return [all_steps[0]]

    # Guard: fewer steps than requested → return all
    if len(all_steps) <= n_frames:
        return list(all_steps)

    # Evenly sample including first (index 0) and last (index len-1)
    total = len(all_steps)
    indices = set()
    indices.add(0)
    indices.add(total - 1)
    for i in range(1, n_frames - 1):
        idx = round(i * (total - 1) / (n_frames - 1))
        indices.add(idx)

    # If rounding produced fewer than n_frames, fill in gaps
    sorted_indices = sorted(indices)
    while len(sorted_indices) < n_frames:
        # Insert the midpoint of the largest gap
        gaps = [(sorted_indices[k + 1] - sorted_indices[k], k)
                for k in range(len(sorted_indices) - 1)]
        _, gap_start = max(gaps)
        new_idx = (sorted_indices[gap_start] + sorted_indices[gap_start + 1]) // 2
        if new_idx not in indices:
            indices.add(new_idx)
            sorted_indices = sorted(indices)
        else:
            break

    return [all_steps[i] for i in sorted(indices)]


# ---------------------------------------------------------------------------
# Color helpers
# ---------------------------------------------------------------------------

def _hsv_to_rgb(h, s, v):
    """Convert HSV to RGB using colorsys. Returns (r, g, b) floats in [0, 1]."""
    return colorsys.hsv_to_rgb(h, s, v)


# ---------------------------------------------------------------------------
# PML generation
# ---------------------------------------------------------------------------

def generate_pml(checkpoint_dir, n_frames=8, output_dir="pymol_renders"):
    """Generate a PyMOL .pml script as a string.

    Args:
        checkpoint_dir: Path to root checkpoint directory.
        n_frames:       Number of frames to sample for the overlay view.
        output_dir:     Directory where PNG renders will be saved.

    Returns:
        String containing the complete .pml script.
    """
    all_steps = _discover_pdb_steps(checkpoint_dir)
    if not all_steps:
        raise ValueError(f"No PDB steps found in {checkpoint_dir}")

    sampled = _sample_frames(all_steps, n_frames)
    n_sampled = len(sampled)

    lines = []

    # -----------------------------------------------------------------------
    # Preamble
    # -----------------------------------------------------------------------
    lines.append("# PyMOL trajectory render script")
    lines.append("# Generated by generate_pymol_script.py")
    lines.append("")
    lines.append("# ---- Settings ----")
    lines.append("bg_color white")
    lines.append("set ray_opaque_background, off")
    lines.append("set antialias, 2")
    lines.append("set ray_shadows, 0")
    lines.append("")

    # Create output directory
    abs_output_dir = os.path.abspath(output_dir)
    lines.append("# ---- Create output directory ----")
    lines.append("python")
    lines.append("import os")
    lines.append(f"os.makedirs('{abs_output_dir}', exist_ok=True)")
    lines.append("python end")
    lines.append("")

    # -----------------------------------------------------------------------
    # PART 1: Overlay view
    # -----------------------------------------------------------------------
    lines.append("# ================================================================")
    lines.append("# PART 1: Overlay — sampled frames superposed on step-0 target")
    lines.append("# ================================================================")
    lines.append("")

    # Load the reference (step 0) target; always use the very first step
    ref_step_num, ref_pdb_path = all_steps[0]
    ref_name = f"ref_step{ref_step_num:04d}"
    lines.append(f"# Load reference (step 0) for alignment")
    lines.append(f"load {ref_pdb_path}, {ref_name}")
    lines.append(f"color gray70, {ref_name} and chain B")
    lines.append(f"hide everything, {ref_name} and chain A")
    lines.append("")

    # Load each sampled frame and align
    for frame_idx, (step_num, pdb_path) in enumerate(sampled):
        name = f"overlay_step{step_num:04d}"

        # HSV: hue 240 (blue) → 0 (red)
        if n_sampled > 1:
            frac = frame_idx / (n_sampled - 1)
        else:
            frac = 0.0
        hue = (1.0 - frac) * (240.0 / 360.0)   # 240° → 0° in [0,1]
        r, g, b = _hsv_to_rgb(hue, 1.0, 1.0)

        lines.append(f"# Step {step_num} — frame {frame_idx + 1}/{n_sampled}")
        lines.append(f"load {pdb_path}, {name}")
        # Align binder+target of this frame onto the reference target (chain B)
        lines.append(f"align {name} and chain B, {ref_name} and chain B")
        lines.append(f"set_color color_{name}, [{r:.4f}, {g:.4f}, {b:.4f}]")
        lines.append(f"color color_{name}, {name} and chain A")
        lines.append(f"color gray70, {name} and chain B")
        lines.append(f"hide everything, {name} and chain B")
        lines.append("")

    # Show cartoon representation for overlay
    lines.append("# Show cartoon representation")
    lines.append("hide everything")
    lines.append(f"show cartoon, {ref_name} and chain B")
    for step_num, _ in sampled:
        lines.append(f"show cartoon, overlay_step{step_num:04d} and chain A")
    lines.append("")

    # Orient on reference target and store view
    lines.append(f"orient {ref_name} and chain B")
    lines.append("python")
    lines.append("stored.view = cmd.get_view()")
    lines.append("python end")
    lines.append("")

    # Render overlay PNG
    overlay_png = os.path.join(abs_output_dir, "overlay.png")
    lines.append("# Render overlay")
    lines.append(f"ray 1200, 900")
    lines.append(f"png {overlay_png}, dpi=150")
    lines.append("")

    # Hide overlay objects before per-frame gallery
    lines.append("# Hide overlay objects")
    lines.append(f"hide everything, {ref_name}")
    for step_num, _ in sampled:
        lines.append(f"hide everything, overlay_step{step_num:04d}")
    lines.append("")

    # -----------------------------------------------------------------------
    # PART 2: Per-frame gallery
    # -----------------------------------------------------------------------
    lines.append("# ================================================================")
    lines.append("# PART 2: Per-frame gallery — each frame individually")
    lines.append("# ================================================================")
    lines.append("")

    for frame_idx, (step_num, pdb_path) in enumerate(sampled):
        name = f"frame_step{step_num:04d}"
        frame_png = os.path.join(abs_output_dir, f"frame_{step_num:04d}.png")

        lines.append(f"# --- Frame {frame_idx + 1}/{n_sampled}: step {step_num} ---")
        lines.append(f"load {pdb_path}, {name}")
        lines.append(f"show cartoon, {name}")

        # Align to reference target
        lines.append(f"align {name} and chain B, {ref_name} and chain B")

        # Color binder by B-factor (logit-space pLDDT) using blue_white_red spectrum
        lines.append(
            f"spectrum b, blue_white_red, {name} and chain A, minimum=-5, maximum=5"
        )
        lines.append(f"color gray70, {name} and chain B")

        # Restore stored camera view
        lines.append("python")
        lines.append("cmd.set_view(stored.view)")
        lines.append("python end")

        # Render
        lines.append(f"ray 1200, 900")
        lines.append(f"png {frame_png}, dpi=150")

        # Hide this frame before next
        lines.append(f"hide everything, {name}")
        lines.append("")

    # -----------------------------------------------------------------------
    # Done
    # -----------------------------------------------------------------------
    lines.append("quit")
    lines.append("")

    return "\n".join(lines)


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(
        description="Generate a PyMOL .pml script for BindCraft trajectories."
    )
    parser.add_argument(
        "--checkpoint_dir",
        required=True,
        help="Root checkpoint directory containing step_*/ subdirectories.",
    )
    parser.add_argument(
        "--output",
        default="trajectory_render.pml",
        help="Output .pml file path (default: trajectory_render.pml).",
    )
    parser.add_argument(
        "--n_frames",
        type=int,
        default=8,
        help="Number of frames to sample (default: 8).",
    )
    parser.add_argument(
        "--render_dir",
        default="pymol_renders",
        help="Directory for PNG output files (default: pymol_renders).",
    )
    args = parser.parse_args()

    pml_content = generate_pml(
        checkpoint_dir=args.checkpoint_dir,
        n_frames=args.n_frames,
        output_dir=args.render_dir,
    )

    output_path = os.path.abspath(args.output)
    with open(output_path, "w") as f:
        f.write(pml_content)

    print(f"Written: {output_path}")
    all_steps = _discover_pdb_steps(args.checkpoint_dir)
    sampled = _sample_frames(all_steps, args.n_frames)
    print(f"Total steps found: {len(all_steps)}")
    print(f"Sampled frames:    {len(sampled)}")
    print(f"Render dir:        {os.path.abspath(args.render_dir)}")


if __name__ == "__main__":
    main()
